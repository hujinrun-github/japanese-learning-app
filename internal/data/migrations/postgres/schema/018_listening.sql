-- Listening reuses lessons and their audio/subtitle assets. Assessment state is
-- separate from reading and speaking so playing a clip does not imply mastery.
CREATE TABLE listening_questions (
    id TEXT PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    position INTEGER NOT NULL DEFAULT 0 CHECK (position >= 0),
    type TEXT NOT NULL DEFAULT 'comprehension',
    prompt TEXT NOT NULL CHECK (length(trim(prompt)) > 0),
    options_json JSONB NOT NULL CHECK (jsonb_typeof(options_json) = 'array' AND jsonb_array_length(options_json) BETWEEN 2 AND 6),
    correct_option_index INTEGER NOT NULL CHECK (correct_option_index >= 0 AND correct_option_index < jsonb_array_length(options_json)),
    explanation TEXT NOT NULL,
    evidence_sentence_index INTEGER NOT NULL DEFAULT 0 CHECK (evidence_sentence_index >= 0),
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
    published BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (lesson_id, position)
);

CREATE TABLE listening_progress (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    lesson_id BIGINT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    stage TEXT NOT NULL DEFAULT 'blind' CHECK (stage IN ('blind','intensive','retest','completed')),
    sentence_index INTEGER NOT NULL DEFAULT 0 CHECK (sentence_index >= 0),
    position_ms BIGINT NOT NULL DEFAULT 0 CHECK (position_ms >= 0),
    bookmarks_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    draft_answers_json JSONB,
    cycle INTEGER NOT NULL DEFAULT 1 CHECK (cycle > 0),
    review_step INTEGER NOT NULL DEFAULT 0 CHECK (review_step BETWEEN 0 AND 3),
    completed_count INTEGER NOT NULL DEFAULT 0 CHECK (completed_count >= 0),
    due_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, lesson_id)
);

CREATE INDEX idx_listening_progress_due ON listening_progress(user_id,due_at);

CREATE TABLE listening_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    lesson_id BIGINT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    cycle INTEGER NOT NULL CHECK (cycle > 0),
    phase TEXT NOT NULL CHECK (phase IN ('blind','retest')),
    assisted BOOLEAN NOT NULL,
    idempotency_key TEXT NOT NULL CHECK (length(idempotency_key) BETWEEN 1 AND 120),
    request_hash TEXT NOT NULL,
    result_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, idempotency_key),
    UNIQUE (user_id, lesson_id, cycle, phase)
);

CREATE INDEX idx_listening_attempts_session ON listening_attempts(user_id,lesson_id,cycle,id);
